    <p>Keberhasilan perkebunan kelapa sawit selama 25 tahun ke depan sangat ditentukan oleh ketepatan memilih varietas bibit bersertifikat yang sesuai dengan kondisi topografi dan jenis tanah lahan Anda.</p>

    <h2>1. Rekomendasi untuk Lahan Gambut & Lahan Marjinal</h2>
    <div class="card">
        <strong>Varietas Disarankan:</strong> DxP Topaz 3 (Asian Agri) dan DxP Dumpy / PPKS Simalungun.<br>
        <strong>Alasan & Saran Teknis:</strong>
        <ul>
            <li>Lahan gambut memiliki struktur tanah lunak dan daya dukung akar yang rendah sehingga sawit rentan miring/tumbang.</li>
            <li>Pilih varietas bertipe <em>Dumpy</em> (batang gemuk, kokoh, dan laju meninggi lambat) serta tahan genangan air.</li>
            <li>Gunakan teknik lubang tanam <strong>hole-in-hole</strong> (lubang di dalam lubang) dan padatkan tanah di sekitar bola akar.</li>
        </ul>
    </div>

    <h2>2. Rekomendasi untuk Lahan Kering & Mineral (Daratan)</h2>
    <div class="card">
        <strong>Varietas Disarankan:</strong> DxP PPKS 239 & PPKS 540, DxP Topaz 1 (Asian Agri), dan DxP Socfindo (Yangambi & La Mé).<br>
        <strong>Alasan & Saran Teknis:</strong>
        <ul>
            <li>Tanah mineral daratan sangat ideal untuk memaksimalkan potensi genetik produksi Tandan Buah Segar (TBS) hingga 35–38 ton/ha/tahun.</li>
            <li>Untuk wilayah dengan musim kemarau panjang atau curah hujan rendah, prioritaskan turunan <strong>Socfindo La Mé</strong> karena paling toleran terhadap kekeringan.</li>
            <li>Pisahkan lapisan tanah atas (<em>top soil</em>) dan bawah (<em>sub soil</em>) saat membuat lubang tanam 60x60x60 cm.</li>
        </ul>
    </div>

    <h2>3. Rekomendasi untuk Lahan Berbukit atau Rawan Penyakit (Ganoderma)</h2>
    <div class="card">
        <strong>Varietas Disarankan:</strong> DxP Topaz 2 (Asian Agri) dan DxP Topaz GT & Socfindo MT Gano.<br>
        <strong>Alasan & Saran Teknis:</strong>
        <ul>
            <li>Pada area berbukit/miring, buatlah teras kontur atau tapak kuda terlebih dahulu untuk mencegah erosi pupuk.</li>
            <li>Pada lahan <em>replanting</em> (peremajaan) eks-sawit yang endemik jamur <em>Ganoderma boninense</em>, wajib menanam varietas moderat tahan Ganoderma (MT Gano / Topaz GT).</li>
            <li>Lakukan sanitasi pembongkaran tunggul kayu lama dan aplikasikan agen hayati <em>Trichoderma sp.</em> di lubang tanam.</li>
        </ul>
    </div>

    <div class="tips">
        <strong>Catatan Penting Sebelum Membeli Bibit:</strong>
        <ul>
            <li>Pastikan benih/bibit memiliki sertifikat resmi dan berasal dari sumber benih terpercaya (PPKS, Asian Agri, Socfindo).</li>
            <li>Lakukan pemesanan bibit minimal 1–2 bulan sebelum jadwal tanam lapangan agar persiapan lubang tanam optimal.</li>
        </ul>
